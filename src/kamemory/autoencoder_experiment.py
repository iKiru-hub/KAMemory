def _deep_merge(base: dict[str, Any], update: dict[str, Any]) -> dict[str, Any]:
    result = deepcopy(base)
    for key, value in update.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = _deep_merge(result[key], value)
        else:
            result[key] = deepcopy(value)
    return result


def normalize_autoencoder_settings(settings: dict[str, Any] | None) -> dict[str, Any]:
    """Merge a partial settings dictionary with defaults and validate it.

    Common flat keys are accepted as conveniences: ``epochs``, ``lr``,
    ``learning_rate``, ``batch_size``, ``save_name``, and ``save_directory``.
    Nested values take precedence over their flat aliases.
    """

    supplied = {} if settings is None else deepcopy(settings)
    if not isinstance(supplied, dict):
        raise TypeError("settings must be a dictionary")

    training_update = supplied.setdefault("training", {})
    if not isinstance(training_update, dict):
        raise TypeError("settings['training'] must be a dictionary")
    for flat, nested in (
        ("epochs", "epochs"),
        ("lr", "learning_rate"),
        ("learning_rate", "learning_rate"),
        ("batch_size", "batch_size"),
    ):
        if flat in supplied:
            value = supplied.pop(flat)
            if nested not in training_update:
                training_update[nested] = value

    save_update = supplied.setdefault("save", {})
    if not isinstance(save_update, dict):
        raise TypeError("settings['save'] must be a dictionary")
    if "save_name" in supplied:
        value = supplied.pop("save_name")
        if "name" not in save_update:
            save_update["name"] = value
    if "save_directory" in supplied:
        value = supplied.pop("save_directory")
        if "directory" not in save_update:
            save_update["directory"] = value

    resolved = _deep_merge(DEFAULT_SETTINGS, supplied)
    network = resolved["network_params"]
    dataset = resolved["dataset"]
    training = resolved["training"]

    if dataset["kind"] != "factorial_track":
        raise ValueError("dataset.kind must be 'factorial_track'")
    if int(network["mec_N_y"]) != 1:
        raise ValueError("the factorial-track generator currently requires mec_N_y == 1")
    if int(network["mec_N_x"]) != int(network["dim_mec"]):
        raise ValueError("mec_N_x must equal dim_mec")
    if int(network["dim_ei"]) != int(network["dim_mec"]) + int(network["dim_lec"]):
        raise ValueError("dim_ei must equal dim_mec + dim_lec")
    if int(network["dim_eo"]) != int(network["dim_ei"]):
        raise ValueError("the autoencoder requires dim_eo == dim_ei")
    if int(network["num_cues"]) != 2:
        raise ValueError("the validated factorial-track protocol currently uses two cues")
    if 2 * int(network["K_lec"]) > int(network["dim_lec"]):
        raise ValueError("dim_lec is too small for two disjoint cue patterns")
    if not 0 < int(network["K_ca1"]) <= int(network["dim_ca1"]):
        raise ValueError("K_ca1 must lie in [1, dim_ca1]")

    layouts = dataset["layouts"]
    if not layouts:
        raise ValueError("at least one cue-position layout is required")
    for layout in layouts:
        positions = np.asarray(layout, dtype=int)
        if len(positions) < 2 or np.any((positions < 0) | (positions >= int(network["mec_N_x"]))):
            raise ValueError("every layout needs at least two valid cue positions")

    positive_dataset_keys = (
        "train_sessions_per_layout",
        "validation_sessions_per_layout",
        "test_sessions_per_layout",
        "train_repeats_per_combination",
        "validation_repeats_per_combination",
        "test_repeats_per_combination",
        "train_cue_free_laps",
        "validation_cue_free_laps",
        "test_cue_free_laps",
    )
    if any(int(dataset[key]) <= 0 for key in positive_dataset_keys):
        raise ValueError("dataset session, repeat, and cue-free-lap counts must be positive")
    if int(training["epochs"]) <= 0 or int(training["batch_size"]) <= 0:
        raise ValueError("epochs and batch_size must be positive")
    if float(training["learning_rate"]) <= 0:
        raise ValueError("learning_rate must be positive")
    if float(training["spatial_loss_weight"]) < 0 or float(training["sensory_loss_weight"]) < 0:
        raise ValueError("loss weights must be non-negative")
    if float(training["spatial_loss_weight"]) + float(training["sensory_loss_weight"]) == 0:
        raise ValueError("at least one loss weight must be positive")
    return resolved


def resolve_device(requested: str | torch.device) -> torch.device:
    if str(requested) != "auto":
        return torch.device(requested)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if hasattr(torch.backends, "mps") and torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def _split_dataset(
    split: str,
    *,
    seed: int,
    network: dict[str, Any],
    dataset: dict[str, Any],
) -> np.ndarray:
    split_index = {"train": 0, "validation": 1, "test": 2}[split]
    sessions = int(dataset[f"{split}_sessions_per_layout"])
    repeats = int(dataset[f"{split}_repeats_per_combination"])
    free_laps = int(dataset[f"{split}_cue_free_laps"])
    chunks = []
    for layout_index, layout in enumerate(dataset["layouts"]):
        for session_index in range(sessions):
            run_seed = (
                int(seed)
                + 10_000_000 * split_index
                + 100_000 * layout_index
                + session_index
            )
            generated = generate_factorial_track(
                track_length=int(network["mec_N_x"]),
                cue_positions=layout,
                repeats_per_combination=repeats,
                cue_free_laps=free_laps,
                spatial_size=int(network["dim_mec"]),
                sensory_size=int(network["dim_lec"]),
                sensory_active=int(network["K_lec"]),
                place_field_sigma=float(network["mec_sigma"]),
                rng=np.random.default_rng(run_seed),
            )
            chunks.append(generated["inputs"])
    return np.ascontiguousarray(np.concatenate(chunks), dtype=np.float32)


def make_factorial_autoencoder_datasets(
    settings: dict[str, Any] | None = None,
) -> dict[str, np.ndarray | dict[str, Any]]:
    """Create independent train/validation/test samples from the paper task."""

    resolved = normalize_autoencoder_settings(settings)
    network = resolved["network_params"]
    dataset = resolved["dataset"]
    arrays = {
        split: _split_dataset(
            split,
            seed=int(resolved["seed"]),
            network=network,
            dataset=dataset,
        )
        for split in ("train", "validation", "test")
    }
    summary = {
        "generator": "kamemory.data.generate_factorial_track",
        "distribution": "E3/E6/E7/E9 factorial spatial+sensory track",
        "independent_split_rng_streams": True,
        "samples": {split: int(len(values)) for split, values in arrays.items()},
        "shape": {split: list(values.shape) for split, values in arrays.items()},
        "sha256": {split: array_digest(values) for split, values in arrays.items()},
    }
    return {**arrays, "summary": summary}


def _component_loss(
    reconstruction: torch.Tensor,
    target: torch.Tensor,
    *,
    spatial_dim: int,
    spatial_weight: float,
    sensory_weight: float,
) -> torch.Tensor:
    spatial = nn.functional.mse_loss(
        reconstruction[:, :spatial_dim], target[:, :spatial_dim]
    )
    sensory = nn.functional.mse_loss(
        reconstruction[:, spatial_dim:], target[:, spatial_dim:]
    )
    return (spatial_weight * spatial + sensory_weight * sensory) / (
        spatial_weight + sensory_weight
    )


@torch.no_grad()
def evaluate_factorial_autoencoder(
    model: Autoencoder,
    data: np.ndarray,
    *,
    network_params: dict[str, Any],
    training_settings: dict[str, Any],
    batch_size: int,
    device: str | torch.device,
) -> dict[str, float]:
    """Evaluate reconstruction and latent-code quality on a dataset split."""

    device = torch.device(device)
    spatial_dim = int(network_params["dim_mec"])
    sensory_active = int(network_params["K_lec"])
    input_dim = int(network_params["dim_ei"])
    sensory_dim = int(network_params["dim_lec"])
    loader = DataLoader(
        TensorDataset(torch.as_tensor(data, dtype=torch.float32)),
        batch_size=int(batch_size),
        shuffle=False,
    )
    was_training = model.training
    model.eval()
    model.to(device)
    totals = {
        "squared": 0.0,
        "spatial_squared": 0.0,
        "sensory_squared": 0.0,
        "cosine": 0.0,
        "spatial_cosine": 0.0,
        "sensory_cosine": 0.0,
        "spatial_peak_correct": 0.0,
        "sensory_top_k_overlap": 0.0,
        "latent_active": 0.0,
        "latent_mean": 0.0,
    }
    count = 0
    for (batch,) in loader:
        batch = batch.to(device)
        reconstruction, code = model(batch, ca1=True)
        spatial_target = batch[:, :spatial_dim]
        sensory_target = batch[:, spatial_dim:]
        spatial_output = reconstruction[:, :spatial_dim]
        sensory_output = reconstruction[:, spatial_dim:]
        batch_count = len(batch)
        count += batch_count
        totals["squared"] += nn.functional.mse_loss(
            reconstruction, batch, reduction="sum"
        ).item()
        totals["spatial_squared"] += nn.functional.mse_loss(
            spatial_output, spatial_target, reduction="sum"
        ).item()
        totals["sensory_squared"] += nn.functional.mse_loss(
            sensory_output, sensory_target, reduction="sum"
        ).item()
        totals["cosine"] += nn.functional.cosine_similarity(
            reconstruction, batch, dim=1
        ).sum().item()
        totals["spatial_cosine"] += nn.functional.cosine_similarity(
            spatial_output, spatial_target, dim=1
        ).sum().item()
        totals["sensory_cosine"] += nn.functional.cosine_similarity(
            sensory_output, sensory_target, dim=1
        ).sum().item()
        totals["spatial_peak_correct"] += (
            spatial_output.argmax(dim=1) == spatial_target.argmax(dim=1)
        ).sum().item()
        predicted = sensory_output.topk(sensory_active, dim=1).indices
        target_mask = sensory_target > 0.5
        totals["sensory_top_k_overlap"] += target_mask.gather(1, predicted).sum().item()
        totals["latent_active"] += (code > 0.5).sum().item()
        totals["latent_mean"] += code.sum().item()
    model.train(was_training)
    spatial_mse = totals["spatial_squared"] / (count * spatial_dim)
    sensory_mse = totals["sensory_squared"] / (count * sensory_dim)
    spatial_weight = float(training_settings["spatial_loss_weight"])
    sensory_weight = float(training_settings["sensory_loss_weight"])
    return {
        "mse": totals["squared"] / (count * input_dim),
        "weighted_mse": (
            spatial_weight * spatial_mse + sensory_weight * sensory_mse
        )
        / (spatial_weight + sensory_weight),
        "spatial_mse": spatial_mse,
        "sensory_mse": sensory_mse,
        "cosine": totals["cosine"] / count,
        "spatial_cosine": totals["spatial_cosine"] / count,
        "sensory_cosine": totals["sensory_cosine"] / count,
        "spatial_peak_accuracy": totals["spatial_peak_correct"] / count,
        "sensory_top_k_f1": totals["sensory_top_k_overlap"]
        / (count * sensory_active),
        "latent_active_count": totals["latent_active"] / count,
        "latent_mean_activity": totals["latent_mean"]
        / (count * int(network_params["dim_ca1"])),
    }


def _json_ready(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, torch.device):
        return str(value)
    if isinstance(value, dict):
        return {key: _json_ready(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [_json_ready(item) for item in value]
    return value


def run_autoencoder_experiment(
    settings: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Run dataset generation, training, testing, and optional persistence.

    The returned dictionary contains the in-memory ``model`` plus a JSON-safe
    ``report``. If saving is enabled, ``session_path`` points to a standard
    KAMemory checkpoint loadable with :func:`load_autoencoder_session`.
    """

    resolved = normalize_autoencoder_settings(settings)
    device = resolve_device(resolved["device"])
    previous_deterministic = torch.are_deterministic_algorithms_enabled()
    seed_everything(int(resolved["seed"]), bool(resolved["deterministic"]))
    try:
        data = make_factorial_autoencoder_datasets(resolved)
        network = resolved["network_params"]
        training = resolved["training"]
        evaluation = resolved["evaluation"]
        model = Autoencoder(
            input_dim=int(network["dim_ei"]),
            encoding_dim=int(network["dim_ca1"]),
            K=int(network["K_ca1"]),
            beta=float(network["beta_ca1"]),
            use_bias=bool(network.get("bias", True)),
        ).to(device)

        initial_metrics = evaluate_factorial_autoencoder(
            model,
            data["test"],
            network_params=network,
            training_settings=training,
            batch_size=int(evaluation["batch_size"]),
            device=device,
        )
        reference_metrics = None
        reference_name = evaluation.get("reference_checkpoint")
        if reference_name:
            _, reference = load_autoencoder_session(reference_name, map_location=device)
            if (
                reference._input_dim != int(network["dim_ei"])
                or reference._encoding_dim != int(network["dim_ca1"])
            ):
                raise ValueError("reference checkpoint architecture does not match settings")
            reference_metrics = evaluate_factorial_autoencoder(
                reference,
                data["test"],
                network_params=network,
                training_settings=training,
                batch_size=int(evaluation["batch_size"]),
                device=device,
            )

        train_tensor = torch.as_tensor(data["train"], dtype=torch.float32)
        loader_generator = torch.Generator().manual_seed(int(resolved["seed"]) + 40_000_000)
        loader = DataLoader(
            TensorDataset(train_tensor),
            batch_size=int(training["batch_size"]),
            shuffle=True,
            num_workers=int(training["num_workers"]),
            generator=loader_generator,
            pin_memory=device.type == "cuda",
        )
        optimizer = torch.optim.Adam(
            model.parameters(),
            lr=float(training["learning_rate"]),
            weight_decay=float(training["weight_decay"]),
        )
        history = {"train_loss": [], "validation_loss": []}
        best_epoch = 0
        best_loss = float("inf")
        best_state: dict[str, torch.Tensor] | None = None
        epochs_without_improvement = 0
        patience = training["early_stopping_patience"]
        patience = None if patience is None else int(patience)
        verbose = bool(resolved["verbose"])

        for epoch in range(1, int(training["epochs"]) + 1):
            model.train()
            total_loss = 0.0
            total_samples = 0
            for (batch,) in loader:
                batch = batch.to(device, non_blocking=device.type == "cuda")
                optimizer.zero_grad(set_to_none=True)
                reconstruction = model(batch)
                loss = _component_loss(
                    reconstruction,
                    batch,
                    spatial_dim=int(network["dim_mec"]),
                    spatial_weight=float(training["spatial_loss_weight"]),
                    sensory_weight=float(training["sensory_loss_weight"]),
                )
                loss.backward()
                max_grad_norm = training.get("max_grad_norm")
                if max_grad_norm is not None:
                    nn.utils.clip_grad_norm_(model.parameters(), float(max_grad_norm))
                optimizer.step()
                total_loss += loss.item() * len(batch)
                total_samples += len(batch)
            train_loss = total_loss / total_samples
            validation_metrics = evaluate_factorial_autoencoder(
                model,
                data["validation"],
                network_params=network,
                training_settings=training,
                batch_size=int(evaluation["batch_size"]),
                device=device,
            )
            validation_loss = validation_metrics["weighted_mse"]
            history["train_loss"].append(train_loss)
            history["validation_loss"].append(validation_loss)

            if validation_loss < best_loss - float(training["early_stopping_min_delta"]):
                best_loss = validation_loss
                best_epoch = epoch
                best_state = {
                    key: value.detach().cpu().clone()
                    for key, value in model.state_dict().items()
                }
                epochs_without_improvement = 0
            else:
                epochs_without_improvement += 1

            log_every = max(1, int(training["log_every"]))
            if verbose and (epoch == 1 or epoch % log_every == 0):
                print(
                    f"epoch {epoch:4d} | train {train_loss:.6f} | "
                    f"validation {validation_loss:.6f} | best {best_loss:.6f}"
                )
            if patience is not None and epochs_without_improvement >= patience:
                if verbose:
                    print(f"early stopping at epoch {epoch}; best epoch was {best_epoch}")
                break

        if best_state is None:
            raise RuntimeError("training completed without a finite validation checkpoint")
        model.load_state_dict(best_state)
        model.to(device)
        model.eval()
        final_metrics = {
            split: evaluate_factorial_autoencoder(
                model,
                data[split],
                network_params=network,
                training_settings=training,
                batch_size=int(evaluation["batch_size"]),
                device=device,
            )
            for split in ("train", "validation", "test")
        }

        report = {
            "schema_version": 1,
            "experiment": "factorial_track_autoencoder_training",
            "settings": _json_ready(resolved),
            "resolved_device": str(device),
            "runtime": runtime_metadata(),
            "data": data["summary"],
            "optimization": {
                "epochs_completed": len(history["train_loss"]),
                "best_epoch": best_epoch,
                "best_validation_weighted_mse": best_loss,
                "history": history,
            },
            "metrics": {
                "random_initialization_test": initial_metrics,
                "reference_checkpoint": reference_name,
                "reference_checkpoint_test": reference_metrics,
                "trained": final_metrics,
            },
            "checkpoint_contract": {
                "loader": "kamemory.io.load_autoencoder_session",
                "network_params_embedded": True,
                "state_dict_file": "autoencoder.pt",
                "metadata_file": "info.json",
            },
        }

        session_path = None
        if bool(resolved["save"]["enabled"]):
            save_directory = resolved["save"].get("directory")
            save_directory = None if save_directory in (None, "") else Path(save_directory)
            info = {
                **report,
                "network_params": _json_ready(network),
            }
            original_device = next(model.parameters()).device
            model.to("cpu")
            session_path = save_autoencoder_session(
                model,
                info,
                name=resolved["save"].get("name"),
                directory=save_directory,
            )
            model.to(original_device)
            model.eval()
            report["session_path"] = str(session_path)

        return {
            "model": model,
            "report": report,
            "history": history,
            "session_path": session_path,
        }
    finally:
        torch.use_deterministic_algorithms(previous_deterministic)


def load_settings_json(path: str | Path) -> dict[str, Any]:
    with Path(path).open(encoding="utf-8") as handle:
        settings = json.load(handle)
    if not isinstance(settings, dict):
        raise TypeError("the settings JSON root must be an object")
    return settings


